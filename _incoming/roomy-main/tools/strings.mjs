#!/usr/bin/env node
// Localisation generator: src/Roomy/Localization/strings.json is the source of
// truth. It writes the typed accessors (S.g.cs) and the .resx catalogues.
//
//   node tools/strings.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const locDir = path.join(root, 'src', 'Roomy', 'Localization');
const manifest = JSON.parse(fs.readFileSync(path.join(locDir, 'strings.json'), 'utf8'));
const strings = manifest.strings;

// One row per catalogue: the neutral English file plus one .resx per language.
// `field` is the strings.json property, `culture` the .NET culture suffix.
const catalogues = [
  { file: 'Strings.resx', culture: '', field: 'en' },
  { file: 'Strings.ru.resx', culture: 'ru', field: 'ru' },
  { file: 'Strings.zh-Hans.resx', culture: 'zh-Hans', field: 'zh-Hans' },
];

// English is required. A missing translation falls back to English (the app does the same at
// runtime), so new text can land before every language catches up; it is listed as a warning.
const missing = {};
for (const e of strings) {
  if (typeof e.en !== 'string' || e.en.length === 0) throw new Error(`strings.json: "${e.key}" has no English text`);
  for (const { field } of catalogues.slice(1)) {
    if (typeof e[field] !== 'string' || e[field].length === 0) (missing[field] ??= []).push(e.key);
  }
}
for (const [field, keys] of Object.entries(missing))
  console.warn(`warning: ${keys.length} string(s) not translated to ${field} yet, using English: ${keys.join(', ')}`);

const xmlEscape = (s) => s
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;');

const resx = (entries, field) => `<?xml version="1.0" encoding="utf-8"?>
<root>
  <resheader name="resmimetype"><value>text/microsoft-resx</value></resheader>
  <resheader name="version"><value>2.0</value></resheader>
  <resheader name="reader"><value>System.Resources.ResXResourceReader, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value></resheader>
  <resheader name="writer"><value>System.Resources.ResXResourceWriter, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value></resheader>
${entries.map((e) => `  <data name="${e.key}" xml:space="preserve">
    <value>${xmlEscape(e[field] || e.en)}</value>
  </data>`).join('\n')}
</root>
`;

for (const { file, field } of catalogues) {
  fs.writeFileSync(path.join(locDir, file), resx(strings, field));
}

const properties = strings
  .map((e) => `    /// <summary>${e.en.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/\*\//g, '* /')}</summary>\n    public static string ${e.key} => Loc.Get("${e.key}");`)
  .join('\n\n');

fs.writeFileSync(path.join(locDir, 'S.g.cs'), `// <auto-generated>
// Generated from src/Roomy/Localization/strings.json by tools/strings.mjs.
// Add a string there, not here.
// </auto-generated>
namespace Roomy.Localization;

/// <summary>Typed access to every user-facing string. Values follow the system language.</summary>
public static class S
{
${properties}
}
`);

console.log(`strings.json: ${strings.length} strings; S.g.cs and ${catalogues.map((c) => c.file).join(', ')} written`);
